-- 1. Create Extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. Drop existing tables if re-running
DROP TABLE IF EXISTS deposit_rates CASCADE;
DROP TABLE IF EXISTS banks CASCADE;

-- 3. Banks Table
CREATE TABLE banks (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    short_name TEXT NOT NULL,
    group_type TEXT NOT NULL CHECK (group_type IN ('BIG4', 'TMCP', 'DIGITAL')),
    brand_color TEXT NOT NULL,
    logo_url TEXT,
    non_term_rate NUMERIC(4, 2) DEFAULT 0.20,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Deposit Rates Table
CREATE TABLE deposit_rates (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    bank_id UUID NOT NULL REFERENCES banks(id) ON DELETE CASCADE,
    deposit_type TEXT NOT NULL CHECK (deposit_type IN ('ONLINE', 'COUNTER')),
    term_months INT NOT NULL CHECK (term_months IN (1, 3, 6, 9, 12, 18, 24)),
    rate_percent NUMERIC(5, 2) NOT NULL CHECK (rate_percent >= 0 AND rate_percent <= 20),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_bank_type_term UNIQUE (bank_id, deposit_type, term_months)
);

-- 4.1. Rate History Table
CREATE TABLE rate_history (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    bank_id UUID NOT NULL REFERENCES banks(id) ON DELETE CASCADE,
    deposit_type TEXT NOT NULL CHECK (deposit_type IN ('ONLINE', 'COUNTER')),
    term_months INT NOT NULL CHECK (term_months IN (1, 3, 6, 9, 12, 18, 24)),
    rate_percent NUMERIC(5, 2) NOT NULL CHECK (rate_percent >= 0 AND rate_percent <= 20),
    recorded_date DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uq_bank_type_term_date UNIQUE (bank_id, deposit_type, term_months, recorded_date)
);

-- 4.2. Loan Rates Table (Vay Tiền Lãi)
CREATE TABLE IF NOT EXISTS loan_rates (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    bank_id UUID NOT NULL REFERENCES banks(id) ON DELETE CASCADE,
    loan_type TEXT NOT NULL CHECK (loan_type IN ('MORTGAGE', 'AUTO', 'UNSECURED')),
    promo_rate NUMERIC(5, 2) NOT NULL CHECK (promo_rate >= 0 AND promo_rate <= 30),
    promo_months INT NOT NULL DEFAULT 12,
    floating_rate NUMERIC(5, 2) NOT NULL CHECK (floating_rate >= 0 AND floating_rate <= 30),
    early_fee_percent NUMERIC(4, 2) NOT NULL DEFAULT 1.5,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_bank_loan_type UNIQUE (bank_id, loan_type)
);

-- 5. Indexes for fast query lookup
CREATE INDEX idx_deposit_rates_term_type ON deposit_rates(term_months, deposit_type);
CREATE INDEX idx_rate_history_lookup ON rate_history(bank_id, deposit_type, term_months, recorded_date);
CREATE INDEX idx_loan_rates_lookup ON loan_rates(loan_type);
CREATE INDEX idx_banks_group ON banks(group_type);

-- 6. Row Level Security (RLS)
ALTER TABLE banks ENABLE ROW LEVEL SECURITY;
ALTER TABLE deposit_rates ENABLE ROW LEVEL SECURITY;
ALTER TABLE rate_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE loan_rates ENABLE ROW LEVEL SECURITY;

-- Allow anonymous and authenticated read access
CREATE POLICY "Allow public read access on banks" ON banks
    FOR SELECT USING (true);

CREATE POLICY "Allow public read access on deposit_rates" ON deposit_rates
    FOR SELECT USING (true);

CREATE POLICY "Allow public read access on rate_history" ON rate_history
    FOR SELECT USING (true);

CREATE POLICY "Allow public read access on loan_rates" ON loan_rates
    FOR SELECT USING (true);

-- Allow service role / cron write access
CREATE POLICY "Allow service insert/update on deposit_rates" ON deposit_rates
    FOR ALL USING (auth.role() = 'service_role');

CREATE POLICY "Allow service insert/update on rate_history" ON rate_history
    FOR ALL USING (auth.role() = 'service_role');

CREATE POLICY "Allow service insert/update on loan_rates" ON loan_rates
    FOR ALL USING (auth.role() = 'service_role');

